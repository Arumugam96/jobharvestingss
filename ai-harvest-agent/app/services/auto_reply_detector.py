"""Decide whether an inbound email is an automatic reply rather than a person writing back.

Used by every inbound path (Brevo webhook, IMAP poller, Graph poller — all funnel through
outreach_reply_service.record_inbound_replies) and by the stored-reply backfill
(outreach_reply_service.reclassify_auto_replies). An auto-reply is filed in the Mail logs
"Auto-replies" view and never counts as a prospect reply (no ``replied_at`` stamp, no bell
notification).

Three layers, strongest first. Any one strong signal is enough:

1. Headers: RFC 3834 ``Auto-Submitted``, the vendor auto-reply headers (``X-Autoreply``,
   ``X-Autorespond``, Exchange's ``X-MS-Exchange-Organization-AutoReply`` …),
   ``Precedence: auto_reply|bulk|junk``, a null envelope sender (``Return-Path: <>``) and
   ``multipart/report`` (delivery-status reports).
2. Subject: after removing reply/forward prefixes ("RE:", "AW:", "Fwd:") and tags such as
   "[EXTERNAL]", it starts with a known auto-reply marker in any of the common mail-system
   languages ("Automatic reply:", "Out of Office:", "Undeliverable:", "Abwesenheitsnotiz",
   "自动回复" …), or contains an unambiguous one ("out of office", "auto-reply").
3. Body: the fresh part of the message (quoted history cut off) is scored. Wording that
   says it's automated ("this is an automated response", "please do not reply", "is no
   longer with the company") counts on its own. Absence wording ("I am on time off", "out
   of the office", "on leave") or a receipt acknowledgement ("we have received your
   email") counts only with corroboration: a return date ("resuming on", "back on"),
   limited access or a colleague to contact, a ticket number / "will respond within", or
   a "Thank you for your email" opener. A question or engagement ("interested", "please
   share profiles", "call me") pulls the score down, so a person writing "I'm on leave
   till Monday, but interested — can you share profiles?" stays a real reply.

The header names worth carrying through the pollers are in AUTO_REPLY_HEADERS, so a
Graph/IMAP item stores them on ``raw`` and the backfill can re-run this detection later.
"""
from __future__ import annotations

import re
import unicodedata
from typing import Callable, Iterable

# Headers the pollers copy onto each inbound item (and so onto the stored `raw`).
AUTO_REPLY_HEADERS: tuple[str, ...] = (
    "Auto-Submitted",
    "X-Auto-Response-Suppress",
    "X-MS-Exchange-Organization-AutoReply",
    "X-MS-Exchange-Generated-Message-Source",
    "X-Autoreply",
    "X-Autorespond",
    "X-Auto-Reply",
    "X-Autogenerated",
    "X-AutoReply-From",
    "X-Mail-Autoreply",
    "X-FC-MachineGenerated",
    "X-Precedence",
    "Precedence",
    "Return-Path",
    "Content-Type",
)

# Header present with any value (other than an explicit "no") → auto-reply.
_PRESENCE_HEADERS: tuple[str, ...] = (
    "X-Auto-Response-Suppress",
    "X-MS-Exchange-Organization-AutoReply",
    "X-Autoreply",
    "X-Autorespond",
    "X-Auto-Reply",
    "X-Autogenerated",
    "X-AutoReply-From",
    "X-Mail-Autoreply",
    "X-FC-MachineGenerated",
)
_AUTO_PRECEDENCE = {"auto_reply", "auto-reply", "bulk", "junk"}
# Exchange stamps this on mail produced by inbox rules / the OOF assistant.
_GENERATED_SOURCE_RE = re.compile(r"mailbox rules agent|out of office|oof|auto ?reply", re.I)

# Zero-width / BOM / bidi marks some clients put in subjects; dropped before matching.
_INVISIBLE_RE = re.compile("[​-‏‪-‮⁠-⁤﻿]")

# Reply / forward prefixes in many languages, and bracketed tags like "[EXTERNAL]".
_SUBJECT_NOISE_RE = re.compile(
    r"^\s*(?:"
    r"\[[^\]]{0,40}\]|\([^)]{0,40}\)|"
    r"(?:re|fw|fwd|aw|wg|sv|vs|tr|rv|enc|res|antw|odp|vb|ynt|réf|ref|回复|回覆|答复|转发|返信|転送)"
    r"\s*(?:\[\d+\])?\s*[:：]"
    r")\s*",
    re.I,
)

# Subject STARTS with one of these (after the noise above is removed).
_SUBJECT_PREFIX_RE = re.compile(
    r"^(?:"
    # English
    r"automatic reply|auto(?:matic)?[\s-]*(?:reply|response|responder|generated)|autoreply|autoresponse|"
    r"auto\s*:|out of (?:the )?office|ooo\b|on leave|on vacation|on holiday|away from (?:the )?office|"
    r"vacation (?:reply|response|notice|message)|holiday (?:reply|notice)|absence notice|"
    r"read\s*:|not read\s*:|"
    r"undeliverable|undelivered mail|delivery status notification|delivery (?:has )?failed|"
    r"delivery failure|mail delivery (?:failed|failure|subsystem)|returned mail|"
    r"message not delivered|failure notice|"
    # German / Dutch / Scandinavian / Finnish
    r"automatische antwort|abwesenheitsnotiz|abwesend|automatisch antwoord|afwezig|"
    r"autosvar|automatiskt svar|automatisk svar|automaattinen vastaus|poissa|"
    # French / Italian / Spanish / Portuguese
    r"réponse automatique|reponse automatique|absence du bureau|absent du bureau|"
    r"risposta automatica|fuori sede|fuori ufficio|"
    r"respuesta automática|respuesta automatica|fuera de la oficina|"
    r"resposta automática|resposta automatica|fora do escritório|ausente|"
    # Central / Eastern European, Turkish, Indonesian
    r"odpowiedź automatyczna|automatická odpověď|automatikus válasz|răspuns automat|"
    r"автоответ|автоматический ответ|автоматична відповідь|otomatik yanıt|otomatik cevap|"
    r"balasan otomatis|"
    # CJK
    r"自动回复|自動回覆|自動回復|自動応答|自動返信|不在|休假|자동 응답|자동응답|부재"
    r")",
    re.I,
)
# Unambiguous markers that count anywhere in the subject.
_SUBJECT_ANYWHERE_RE = re.compile(
    r"\bout of (?:the )?office\b|\bautomatic reply\b|\bauto[\s-]?reply\b|\bautoreply\b|"
    r"\bauto[\s-]?response\b|\bundeliverable\b|\bdelivery status notification\b|"
    r"\babwesenheitsnotiz\b|réponse automatique|automatische antwort|自动回复|自動応答",
    re.I,
)

# ── Body scoring ──────────────────────────────────────────────────────────────

# Says outright that it's machine-sent: enough on its own.
_BODY_AUTOMATED_RE = re.compile(
    r"this is an? auto(?:mated|matic|-generated|generated)? ?(?:reply|response|message|e-?mail|notification)|"
    r"(?:this|the) (?:e-?mail|message|reply|response) (?:is|was|has been) (?:sent |generated )?automatically|"
    r"auto(?:matically)?[\s-]generated (?:reply|response|message|e-?mail)|"
    r"(?:automated|automatic|auto)[\s-](?:reply|response|responder)\b|"
    r"please do not (?:reply|respond) to this (?:e-?mail|message|address)|"
    r"this (?:mailbox|inbox|e-?mail address) is (?:not|no longer) (?:monitored|in use|active)|"
    r"(?:is|are|am) no longer (?:with|employed (?:by|at|with)|working (?:with|at|for)|part of) "
    r"(?:the |this )?(?:company|organi[sz]ation|firm|business|team)|"
    r"(?:has|have) (?:since )?left (?:the |this )(?:company|organi[sz]ation|firm|business)",
    re.I,
)
# Receipt acknowledgement ("we have received your email"): needs corroboration, since a
# person can open with it too.
_BODY_ACK_RE = re.compile(
    r"\bwe(?:'ve| have) received your (?:e-?mail|message|request|query|enquiry|inquiry|application)\b|"
    r"\byour (?:e-?mail|message|request|query|enquiry|inquiry) has been received\b|"
    r"\bthis is to (?:acknowledge|confirm) (?:the )?receipt\b",
    re.I,
)
_BODY_ACK_FOLLOWUP_RE = re.compile(
    r"\b(?:ticket|reference|case|request) (?:number|no\.?|id|#)|"
    r"\b(?:will|shall) (?:get back|respond|reply|revert)(?: to you)? (?:within|shortly|soon|as soon as|at the earliest)|"
    r"\bwithin \d+ (?:business |working )?(?:hours|days)\b",
    re.I,
)
# A person engaging (asking, asking for a profile, proposing a call) pulls the score down.
_BODY_ENGAGED_RE = re.compile(
    r"\?|\binterested\b|\bplease (?:share|send)\b|\bshare (?:the |your )?(?:profiles?|resumes?|cvs?|details)\b|"
    r"\blet'?s (?:talk|connect|discuss|schedule|speak)\b|\b(?:call|ping) me\b|\bgive me a call\b",
    re.I,
)
# Absence wording: needs one more corroborating signal.
_BODY_ABSENCE_RE = re.compile(
    r"\bout of (?:the )?office\b|\booo\b|"
    r"\b(?:i am|i'm|i’m|i will be|i'll be|i’ll be|currently|presently)\s+(?:currently\s+)?"
    r"(?:away|out|off|travell?ing|on (?:a )?(?:annual |sick |casual |medical |maternity |paternity |parental |"
    r"personal |planned |earned |privilege |vacation |holiday |festival )?"
    r"(?:leave|vacation|holiday|holidays|break|time[\s-]?off|pto|sabbatical|business trip|travel))\b|"
    r"\bon (?:annual|sick|casual|medical|maternity|paternity|parental|personal|planned|earned|privilege) leave\b|"
    r"\bon (?:a )?(?:vacation|holiday|time[\s-]?off|pto|sabbatical)\b|"
    r"\baway from (?:the |my )?(?:office|desk|e-?mail|work)\b|"
    r"\b(?:will be |am )?(?:out|away|off) (?:of (?:the )?office )?(?:from|until|till|through|between)\b",
    re.I,
)
# A return date / resumption.
_BODY_RETURN_RE = re.compile(
    r"\b(?:will be |shall be )?(?:back|returning|resuming|resume|return|rejoining|available again|in the office)\s+"
    r"(?:to (?:the )?office |to work |in (?:the )?office |at work )?(?:on|from|by|after|in|next|tomorrow|monday|"
    r"tuesday|wednesday|thursday|friday|saturday|sunday|\d)|"
    r"\b(?:until|till|through|returning)\s+(?:\d{1,2}(?:st|nd|rd|th)?\b|(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)|"
    r"(?:mon|tue|wed|thu|fri|sat|sun)|next week|tomorrow)|"
    r"\bupon (?:my )?return\b|\bwhen i(?:'m| am| get)? back\b|\bon my return\b",
    re.I,
)
# Limited access / redirect to a colleague.
_BODY_REDIRECT_RE = re.compile(
    r"\blimited (?:access|connectivity|availability)\b|\bno access to (?:my )?e-?mail\b|"
    r"\bdelayed (?:response|reply)\b|\bresponse (?:may|will) be delayed\b|"
    r"\bfor (?:any )?(?:urgent|immediate|important) (?:matters?|queries|query|issues?|requests?|assistance|"
    r"concerns?|support|help)\b|\bin case of (?:any )?(?:urgency|emergency|urgent)\b|\bin my absence\b|"
    r"\bplease (?:contact|reach out to|get in touch with|write to|e-?mail|call)\b|"
    r"\b(?:will|shall) (?:respond|reply|get back)(?: to you(?:r (?:e-?mail|message))?)? "
    r"(?:upon|after|on|when|as soon as)\b",
    re.I,
)
_BODY_THANKS_RE = re.compile(
    r"^\W*(?:hi|hello|dear)?[^.\n]{0,20}?thank(?:s| you) (?:you )?for (?:your|the) (?:e-?mail|mail|message|note)",
    re.I,
)

# Where the quoted history starts in a reply body.
_QUOTE_START_RE = re.compile(
    r"^\s*(?:-{2,}\s*original message\s*-{2,}|_{5,}|"
    r"from:\s.+|sent:\s.+|on .{4,120}wrote:\s*$|"
    r"le .{4,120}a écrit\s*:|am .{4,120}schrieb .{0,80}:|el .{4,120}escribió\s*:|"
    r"&gt;|>)",
    re.I | re.M,
)
_TAG_RE = re.compile(r"<[^>]+>")
_BODY_SCAN = 1500


def _normalize(text: str | None) -> str:
    """NFKC, invisible marks dropped, whitespace collapsed (case kept)."""
    t = unicodedata.normalize("NFKC", str(text or ""))
    t = _INVISIBLE_RE.sub("", t)
    return re.sub(r"[ \t\r\f\v ]+", " ", t).strip()


def clean_subject(subject: str | None) -> str:
    """The subject lower-cased with reply/forward prefixes and [TAGS] stripped."""
    s = _normalize(subject).lower()
    for _ in range(8):  # "RE: [EXTERNAL] FW: …"
        stripped = _SUBJECT_NOISE_RE.sub("", s, count=1)
        if stripped == s:
            break
        s = stripped
    return s.strip()


def subject_is_auto(subject: str | None) -> bool:
    """Does the subject mark an automatic reply / delivery report?"""
    s = clean_subject(subject)
    if not s:
        return False
    return bool(_SUBJECT_PREFIX_RE.match(s) or _SUBJECT_ANYWHERE_RE.search(s))


def fresh_body(body: str | None) -> str:
    """The new text of a message: HTML tags dropped, quoted history (from the first
    "On … wrote:", "From:", "-----Original Message-----" or ">" line) cut off,
    whitespace collapsed, capped at _BODY_SCAN characters."""
    text = _TAG_RE.sub(" ", str(body or ""))
    text = unicodedata.normalize("NFKC", text)
    text = _INVISIBLE_RE.sub("", text)
    m = _QUOTE_START_RE.search(text)
    if m and m.start() > 0:
        text = text[: m.start()]
    text = re.sub(r"\s+", " ", text).strip()
    return text[:_BODY_SCAN]


def body_score(body: str | None) -> int:
    """Auto-reply score of the body's fresh text. 3+ means auto-reply."""
    text = fresh_body(body)
    if not text:
        return 0
    if _BODY_AUTOMATED_RE.search(text):
        return 3
    absence = bool(_BODY_ABSENCE_RE.search(text))
    ack = bool(_BODY_ACK_RE.search(text))
    if not (absence or ack):
        return 0
    score = 2
    if absence and _BODY_RETURN_RE.search(text):
        score += 1
    if absence and _BODY_REDIRECT_RE.search(text):
        score += 1
    if ack and _BODY_ACK_FOLLOWUP_RE.search(text):
        score += 1
    if _BODY_THANKS_RE.search(text):
        score += 1
    if _BODY_ENGAGED_RE.search(text):
        score -= 2
    return score


def headers_are_auto(header: Callable[[str], str]) -> bool:
    """Header-level detection. ``header(name)`` returns that header's value ("" when
    absent), case-insensitively."""
    auto_sub = header("Auto-Submitted").strip().lower()
    if auto_sub and auto_sub != "no":
        return True
    for name in _PRESENCE_HEADERS:
        v = header(name).strip().lower()
        if v and v not in ("no", "false", "0"):
            return True
    if _GENERATED_SOURCE_RE.search(header("X-MS-Exchange-Generated-Message-Source")):
        return True
    for name in ("Precedence", "X-Precedence"):
        if header(name).strip().lower() in _AUTO_PRECEDENCE:
            return True
    if header("Return-Path").strip() == "<>":
        return True
    if "multipart/report" in header("Content-Type").lower():
        return True
    return False


def detect_auto_reply(
    *, subject: str | None, body: str | None, header: Callable[[str], str] | None = None,
) -> bool:
    """True when the message is an automatic reply (see the module docstring)."""
    if header is not None and headers_are_auto(header):
        return True
    if subject_is_auto(subject):
        return True
    return body_score(body) >= 3


def header_getter(*maps: dict | None) -> Callable[[str], str]:
    """A case-insensitive ``header(name)`` over one or more dicts (first hit wins);
    list values are joined with ", "."""
    lowered: list[dict[str, object]] = [
        {str(k).lower(): v for k, v in m.items()} for m in maps if isinstance(m, dict)
    ]

    def get(name: str) -> str:
        """Header value for ``name`` ("" when absent)."""
        key = name.lower()
        for m in lowered:
            v = m.get(key)
            if v:
                return ", ".join(map(str, v)) if isinstance(v, list) else str(v)
        return ""

    return get


def pick_headers(header: Callable[[str], str], names: Iterable[str] = AUTO_REPLY_HEADERS) -> dict[str, str]:
    """{name: value} for the given headers that are present (for a poller item)."""
    out: dict[str, str] = {}
    for name in names:
        v = header(name).strip()
        if v:
            out[name] = v
    return out
